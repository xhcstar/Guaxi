/// 去掉自治区名里的民族词，让「新疆」「广西」「宁夏」这类简称能对上前缀。
fn drop_ethnic(name: &str) -> String {
    const WORDS: [&str; 10] = [
        "维吾尔",
        "壮族",
        "回族",
        "蒙古",
        "哈萨克",
        "柯尔克孜",
        "土家",
        "苗族",
        "藏族",
        "布依",
    ];
    let mut out = name.to_string();
    for word in WORDS {
        out = out.replace(word, "");
    }
    out
}

fn normalize(name: &str) -> String {
    name.trim()
        .trim_end_matches("特别行政区")
        .trim_end_matches("自治区")
        .trim_end_matches("省")
        .trim_end_matches("市")
        .to_string()
}

/// 省级名称 → 它的地级市；识别不出省级时返回空，由调用方继续兜底。
pub(crate) fn province_cities(name: &str) -> Vec<Place> {
    let text = name.trim();
    if text.is_empty() {
        return Vec::new();
    }
    let target = normalize(text);
    let matched = PROVINCES.iter().find(|(province, _)| {
        text.contains(province) || (target.len() >= 2 && normalize(province) == target)
    });
    // 用户常只写简称（「新疆」「内蒙」「广西」）：简称要么是省份名去掉民族词后的
    // 前缀，要么是省份名的前缀，两种都算命中。
    let matched = matched.or_else(|| {
        if target.len() < 2 {
            return None;
        }
        PROVINCES.iter().find(|(province, _)| {
            let short = normalize(province);
            short.starts_with(target.as_str())
                || drop_ethnic(&short).starts_with(&drop_ethnic(&target))
        })
    });
    let Some((province, cities)) = matched else {
        return Vec::new();
    };
    cities
        .iter()
        .map(|(city, adcode, lng, lat)| Place {
            id: format!("region-{adcode}"),
            name: (*city).to_string(),
            address: format!("{province}{city}"),
            city: (*city).to_string(),
            adcode: (*adcode).to_string(),
            city_code: String::new(),
            lng: *lng,
            lat: *lat,
            source: "region".to_string(),
        })
        .collect()
}
