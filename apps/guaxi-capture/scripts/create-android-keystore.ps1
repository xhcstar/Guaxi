<#
.SYNOPSIS
    Generate a release keystore for Android APK signing.
.DESCRIPTION
    Creates a new Java KeyStore (JKS) file and the corresponding
    keystore.properties file needed by the Android Gradle build.
    Run this script once before your first android:build.
.PARAMETER KeystorePassword
    Password for the keystore file. Default: guaxi2025
.PARAMETER KeyAlias
    Alias name for the key entry. Default: guaxi
.PARAMETER KeyPassword
    Password for the key entry. Default: same as KeystorePassword.
.PARAMETER ValidityDays
    Validity period in days. Default: 10000 (~27 years).
.PARAMETER DName
    X.500 Distinguished Name for the certificate.
    Default: "CN=Guaxi, OU=Guaxi, O=Guaxi, L=Unknown, ST=Unknown, C=CN"
.EXAMPLE
    .\create-android-keystore.ps1
.EXAMPLE
    .\create-android-keystore.ps1 -KeystorePassword "MyStr0ngP@ss!" -KeyAlias "myapp"
#>

param(
    [string]$KeystorePassword = "guaxi2025",
    [string]$KeyAlias = "guaxi",
    [string]$KeyPassword = "",
    [int]$ValidityDays = 10000,
    [string]$DName = "CN=Guaxi, OU=Guaxi, O=Guaxi, L=Unknown, ST=Unknown, C=CN"
)

$ErrorActionPreference = "Continue"

# Use KeystorePassword as KeyPassword when not explicitly set
if ([string]::IsNullOrWhiteSpace($KeyPassword)) {
    $KeyPassword = $KeystorePassword
}

# Resolve the android project root (gen/android/)
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$ProjectRoot = Resolve-Path "$ScriptDir\.."
$AndroidRoot = "$ProjectRoot\src-tauri\gen\android"

if (-not (Test-Path $AndroidRoot)) {
    Write-Host "ERROR: Android project not found at: $AndroidRoot"
    Write-Host "Run 'npm run android:init' first to generate the Android project."
    exit 1
}

$KeystoreFile = "$AndroidRoot\release.keystore"
$PropertiesFile = "$AndroidRoot\keystore.properties"

# Check for keytool
$keytool = Get-Command "keytool" -ErrorAction SilentlyContinue
if (-not $keytool) {
    # Try to find keytool under JAVA_HOME
    $javaHome = $env:JAVA_HOME
    if ($javaHome -and (Test-Path "$javaHome\bin\keytool.exe")) {
        $keytool = "$javaHome\bin\keytool.exe"
    } else {
        Write-Host "ERROR: keytool not found in PATH or JAVA_HOME."
        Write-Host "Make sure JDK is installed and JAVA_HOME is set."
        exit 1
    }
} else {
    $keytool = $keytool.Source
}

Write-Host "========================================"
Write-Host "  Guaxi Android Release Keystore Generator"
Write-Host "========================================"
Write-Host ""
Write-Host "Keystore path : $KeystoreFile"
Write-Host "Properties    : $PropertiesFile"
Write-Host "Key alias     : $KeyAlias"
Write-Host "Validity      : $ValidityDays days"
Write-Host ""

# Remove existing keystore if any
if (Test-Path $KeystoreFile) {
    Write-Host "[INFO] Existing keystore found. Removing..."
    Remove-Item $KeystoreFile -Force
}

# Generate keystore
Write-Host "[INFO] Generating keystore..."
$keytoolArgs = @(
    "-genkey",
    "-v",
    "-keystore", "`"$KeystoreFile`"",
    "-alias", $KeyAlias,
    "-keyalg", "RSA",
    "-keysize", "2048",
    "-validity", $ValidityDays,
    "-storepass", $KeystorePassword,
    "-keypass", $KeyPassword,
    "-dname", "`"$DName`""
)

# Use cmd /c to avoid PowerShell treating keytool's stderr output as errors
$cmdArgs = "/c `"`"$keytool`" $($keytoolArgs -join ' ')`""
$process = Start-Process -FilePath "cmd.exe" -ArgumentList $cmdArgs -NoNewWindow -Wait -PassThru
if ($process.ExitCode -ne 0) {
    Write-Host "ERROR: keytool failed with exit code $($process.ExitCode)"
    exit 1
}

Write-Host "[INFO] Keystore generated successfully."

# Write keystore.properties
$propertiesContent = @"
# Android release signing keystore properties
# Auto-generated by scripts/create-android-keystore.ps1
# DO NOT commit this file to version control!
storeFile=release.keystore
storePassword=$KeystorePassword
keyAlias=$KeyAlias
keyPassword=$KeyPassword
"@

Set-Content -Path $PropertiesFile -Value $propertiesContent -Encoding UTF8
Write-Host "[INFO] keystore.properties written."

Write-Host ""
Write-Host "========================================"
Write-Host "  Keystore generation complete!"
Write-Host "========================================"
Write-Host ""
Write-Host "Next step: run 'npm run android:build' to build the signed release APK."
Write-Host "The signed APK will be at: src-tauri\gen\android\app\build\outputs\apk\release\"
Write-Host ""
Write-Host "IMPORTANT: Keep your keystore file and passwords safe!"
Write-Host "  - release.keystore and keystore.properties are git-ignored"
Write-Host "  - Back them up securely - losing them means you cannot update your app on stores"
